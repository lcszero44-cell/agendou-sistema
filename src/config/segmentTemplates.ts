export function getTemplateByStoreIdOrSegment(
  storeId?: string | null,
  segment?: SegmentKey | null
): SegmentTemplateBundle {
  if (segment && SEGMENT_TEMPLATES[segment]) {
    return SEGMENT_TEMPLATES[segment];
  }
  const matched = Object.values(SEGMENT_TEMPLATES).find(
    (tpl) => tpl.store.storeId === storeId || tpl.store.slug === storeId
  );
  return matched || SEGMENT_TEMPLATES.odontologia;
}
